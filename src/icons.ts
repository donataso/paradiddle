export function icon(name: string): string {
  return `<svg class="ico" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${PATHS[name]}</svg>`;
}

export function fillIcons(root: ParentNode = document) {
  root.querySelectorAll<HTMLElement>('[data-icon]').forEach(el => {
    el.innerHTML = icon(el.dataset.icon!);
  });
}

const CONFIRM_MS = 3000;
const timers = new WeakMap<HTMLElement, number>();

export function disarm(btn: HTMLElement) {
  clearTimeout(timers.get(btn));
  btn.classList.remove('armed');
  btn.querySelector('.confirm')?.remove();
}

export function confirmClick(btn: HTMLElement, onConfirm: () => void) {
  if (btn.classList.contains('armed')) {
    disarm(btn);
    return onConfirm();
  }
  btn.classList.add('armed');
  btn.insertAdjacentHTML('beforeend', '<span class="confirm">Delete?</span>');
  timers.set(btn, window.setTimeout(() => disarm(btn), CONFIRM_MS));
}
